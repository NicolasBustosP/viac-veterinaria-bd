-- Cobro de servicio dentro de un evento clinico, liquidado bajo un contrato de afiliacion.
-- El saldo pendiente (monto_facturado - monto_pagado) se calcula en las consultas, no se almacena.
-- cod_razon_saldo solo aplica cuando queda saldo pendiente.
CREATE TABLE cobro_servicio (
    id_cobro         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    fecha_realizacion DATE          NOT NULL,
    monto_facturado  NUMBER(12,2)  NOT NULL,
    monto_pagado     NUMBER(12,2)  DEFAULT 0 NOT NULL,
    fecha_pago       DATE,
    cod_razon_saldo  VARCHAR2(10),
    id_evento        NUMBER(10)    NOT NULL,
    cedula_personal  VARCHAR2(15)  NOT NULL,
    num_contrato     VARCHAR2(20)  NOT NULL,
    cod_servicio     VARCHAR2(15)  NOT NULL,
    CONSTRAINT pk_cobro_servicio PRIMARY KEY (id_cobro),
    CONSTRAINT fk_cobro_evento FOREIGN KEY (id_evento) REFERENCES evento_clinico (id_evento),
    CONSTRAINT fk_cobro_personal FOREIGN KEY (cedula_personal) REFERENCES personal (cedula_personal),
    CONSTRAINT fk_cobro_contrato FOREIGN KEY (num_contrato) REFERENCES contrato_afiliacion (num_contrato),
    CONSTRAINT fk_cobro_servicio FOREIGN KEY (cod_servicio) REFERENCES servicio (cod_servicio),
    CONSTRAINT ck_cobro_facturado CHECK (monto_facturado >= 0),
    CONSTRAINT ck_cobro_pagado CHECK (monto_pagado >= 0 AND monto_pagado <= monto_facturado),
    CONSTRAINT ck_cobro_fecha_pago CHECK (monto_pagado = 0 OR fecha_pago IS NOT NULL),
    CONSTRAINT ck_cobro_razon CHECK (cod_razon_saldo IS NULL OR monto_pagado < monto_facturado)
);
