-- Evento clinico (cita, examen, procedimiento o control).
-- id_evento_origen enlaza con el evento previo que lo origino (NULL si es el primero).
-- UNIQUE en id_evento_origen: un evento origina como maximo un evento derivado.
-- cod_cubiculo es NULL cuando el evento no requiere internacion ni cirugia.
CREATE TABLE evento_clinico (
    id_evento              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    tipo_evento            VARCHAR2(15) NOT NULL,
    fecha_hora_programada  TIMESTAMP    NOT NULL,
    fecha_hora_realizacion TIMESTAMP,
    cod_historia_clinica   VARCHAR2(20) NOT NULL,
    cedula_personal        VARCHAR2(15) NOT NULL,
    cod_cubiculo           VARCHAR2(10),
    id_evento_origen       NUMBER(10),
    CONSTRAINT pk_evento_clinico PRIMARY KEY (id_evento),
    CONSTRAINT fk_evento_paciente FOREIGN KEY (cod_historia_clinica) REFERENCES paciente (cod_historia_clinica),
    CONSTRAINT fk_evento_personal FOREIGN KEY (cedula_personal) REFERENCES personal (cedula_personal),
    CONSTRAINT fk_evento_cubiculo FOREIGN KEY (cod_cubiculo) REFERENCES cubiculo (cod_cubiculo),
    CONSTRAINT fk_evento_origen FOREIGN KEY (id_evento_origen) REFERENCES evento_clinico (id_evento),
    CONSTRAINT uq_evento_origen UNIQUE (id_evento_origen),
    CONSTRAINT ck_evento_tipo CHECK (tipo_evento IN ('CITA', 'EXAMEN', 'PROCEDIMIENTO', 'CONTROL')),
    CONSTRAINT ck_evento_origen_distinto CHECK (id_evento_origen IS NULL OR id_evento_origen <> id_evento)
);
